const { chromium }=require('@playwright/test')
const fs=require('node:fs'),assert=require('node:assert/strict')
const base=process.env.DEMO_TEST_URL||'http://localhost:3199'
async function main(){
 const browser=await chromium.launch({channel:'msedge',headless:true})
 const context=await browser.newContext({viewport:{width:1600,height:1000},serviceWorkers:'block'})
 const page=await context.newPage(),errors=[],blocked=[]
 page.on('pageerror',e=>errors.push(e.message))
 await context.route('**/*',r=>{const u=new URL(r.request().url());if(!['localhost','127.0.0.1'].includes(u.hostname)&&u.protocol.startsWith('http')){blocked.push(u.hostname);return r.abort()}return r.continue()})
 const email=`browser-${Date.now()}@example.invalid`,password='Demo-rehearsal-123'
 try{
  const status=await context.request.get(base+'/api/local/status',{timeout:60000});assert.equal(status.status(),200,await status.text())
  await page.goto(base+'/login')
  await page.getByRole('button',{name:'创建账号',exact:true}).click()
  await page.getByLabel('邮箱',{exact:true}).fill(email)
  await page.getByLabel('昵称',{exact:true}).fill('演示新同学')
  await page.locator('input[autocomplete="new-password"]').fill(password)
  await page.getByRole('button',{name:'注册并登录',exact:true}).click()
  await page.waitForURL('**/dashboard',{timeout:60000})
  await page.goto(base+'/dashboard?enter=workspace')
  const input=page.locator('.agent-chat-composer input')
  await input.waitFor({state:'visible',timeout:30000})
  for(const [i,q] of ['科技策略','降低回撤','加入黄金'].entries()){
   await input.fill(q);await input.press('Enter')
   await page.locator('.agent-chat .strategy-card').nth(i).waitFor({state:'visible',timeout:30000})
   await page.waitForFunction(()=>!document.querySelector('.agent-chat-composer input').disabled)
  }
  assert.equal(await page.locator('.agent-chat .strategy-card').count(),3)
  await page.locator('.agent-chat .strategy-deploy').last().click()
  await page.waitForTimeout(800)
  let book=await (await context.request.get(base+'/api/sandbox')).json()
  assert.equal(book.executions.length,1,JSON.stringify(book))
  assert.ok(book.positions.length>0)
  await page.reload()
  await page.goto(base+'/dashboard?enter=workspace')
  await page.locator('.agent-chat .strategy-card').nth(2).waitFor({state:'visible',timeout:30000})
  fs.mkdirSync('test-results/local-demo',{recursive:true})
  await page.screenshot({path:'test-results/local-demo/offline-zh.png',fullPage:true})
  await page.getByRole('button',{name:'切换为英文',exact:true}).click()
  await page.screenshot({path:'test-results/local-demo/offline-en.png',fullPage:true})
  await page.goto(base+'/account')
  await page.getByRole('button',{name:'Sign out',exact:true}).click()
  await page.waitForURL('**/login')
  await page.getByLabel('Email',{exact:true}).fill(email)
  await page.getByLabel('Password',{exact:true}).fill(password)
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await page.waitForURL('**/dashboard')
  book=await (await context.request.get(base+'/api/sandbox')).json()
  assert.equal(book.executions.length,1)
  assert.deepEqual(errors,[])
  assert.deepEqual(blocked,[])
  await context.storageState({path:'test-results/local-demo/session.json'})
  console.log('PASS browser: real fresh local signup; three cards; paper execution; reload; English/Chinese; logout/login; no external requests; no page errors.')
 }catch(e){fs.mkdirSync('test-results/local-demo',{recursive:true});await page.screenshot({path:'test-results/local-demo/failure.png'});throw e}finally{await browser.close()}
}
main().catch(e=>{console.error(e);process.exitCode=1})
