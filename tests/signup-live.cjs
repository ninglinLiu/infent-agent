const { chromium, expect } = require('@playwright/test')
const { randomUUID, randomBytes } = require('node:crypto')
const { writeFileSync } = require('node:fs')
const assert = require('node:assert/strict')

;(async () => {
  if (process.env.INFENT_STAGING !== '1') throw new Error('Signup smoke is staging-only; production account creation is forbidden.')
  const browser = await chromium.launch({ channel: 'msedge' })
  const context = await browser.newContext({ baseURL: 'http://localhost:3107', viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
  const page = await context.newPage()
  const errors = []
  const email = `signup-qa-${randomUUID()}@example.com`
  const password = randomBytes(24).toString('hex')
  const cleanup = { email, id: null }
  const saveCleanup = () => writeFileSync('test-results/signup-cleanup.json', JSON.stringify(cleanup))
  page.on('pageerror', error => errors.push(error.message))
  try {
    const settings = await context.request.get('https://sscjolfuydqmskqzfppn.supabase.co/auth/v1/settings', { headers: { apikey: process.env.TEST_SUPABASE_PUBLIC_KEY } })
    assert.equal(settings.status(), 200)
    assert.equal((await settings.json()).mailer_autoconfirm, true, 'Email confirmation must be disabled before testing signup')
    await page.goto('/login')
    await page.getByRole('button', { name: '创建账号', exact: true }).click()
    await page.getByRole('button', { name: '注册并登录', exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: '忘记密码？', exact: true }).count(), 0)
    await page.screenshot({ path: 'docs/account-validation/registration-no-email.png' })
    await page.getByLabel('昵称', { exact: true }).fill('Signup QA')
    await page.getByLabel('邮箱', { exact: true }).fill(email)
    await page.locator('input[type=password]').fill(password)
    saveCleanup()
    const registered = page.waitForResponse(response => response.url().includes('/auth/v1/signup') && response.request().method() === 'POST')
    await page.getByRole('button', { name: '注册并登录', exact: true }).click()
    const signup = await registered
    assert.equal(signup.status(), 200)
    await page.waitForURL('**/dashboard')
    const initialProfile = await context.request.get('/api/profile')
    assert.equal(initialProfile.status(), 200, 'Signup must immediately establish a real session accepted by the server')
    cleanup.id = (await initialProfile.json()).profile.id
    assert.ok(cleanup.id)
    saveCleanup()
    await page.goto('/account')
    await page.getByLabel('昵称', { exact: true }).waitFor()
    await expect(page.getByLabel('昵称', { exact: true })).toHaveValue('Signup QA', { timeout: 30_000 })
    await page.getByLabel('昵称', { exact: true }).fill('Saved signup QA')
    await page.getByRole('button', { name: '保存资料', exact: true }).click()
    await page.getByText('个人资料已保存。', { exact: true }).waitFor()
    await page.getByRole('button', { name: '退出登录', exact: true }).click()
    await page.waitForURL('**/login')
    assert.equal((await context.request.get('/api/profile')).status(), 401)
    await page.getByRole('button', { name: '创建账号', exact: true }).click()
    await page.getByLabel('昵称', { exact: true }).fill('Duplicate QA')
    await page.getByLabel('邮箱', { exact: true }).fill(email)
    await page.locator('input[type=password]').fill(password)
    await page.getByRole('button', { name: '注册并登录', exact: true }).click()
    await page.getByText('这个邮箱已经注册，请直接登录。', { exact: true }).waitFor()
    await page.getByRole('button', { name: '已有账号？登录', exact: true }).click()
    await page.locator('input[type=password]').fill(password)
    await page.getByRole('button', { name: '登录', exact: true }).click()
    await page.waitForURL('**/dashboard')
    await page.goto('/account')
    await page.getByLabel('昵称', { exact: true }).waitFor()
    await expect(page.getByLabel('昵称', { exact: true })).toHaveValue('Saved signup QA', { timeout: 30_000 })
    assert.equal((await context.request.get('/api/profile')).status(), 200)
    await page.getByRole('button', { name: '退出登录', exact: true }).click()
    await page.waitForURL('**/login')
    assert.deepEqual(errors, [])
    console.log(JSON.stringify({ emailConfirmation: 'disabled', signupSession: 'passed', profilePersistence: 'passed', duplicateSignup: 'rejected', passwordLogin: 'passed', logout: 'passed', browserErrors: 0 }))
  } finally { await context.close(); await browser.close() }
})().catch(error => { console.error(error.message); process.exitCode = 1 })
