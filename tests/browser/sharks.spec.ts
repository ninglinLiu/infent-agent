import { test, expect } from './fixtures'

test('shark backdrop animates, pauses, and leaves restored chat usable', async ({ page }) => {
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.route('**/api/market/**', route => route.fulfill({ status: 503, json: { error: 'UI fixture: feed unavailable' } }))
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/dashboard?enter=workspace')
  const canvas = page.locator('canvas[data-sharks-ready="true"]')
  await expect(canvas).toBeVisible()
  const frame = () => canvas.evaluate((el: HTMLCanvasElement) => el.toDataURL())
  const first = await frame()
  await expect.poll(frame).not.toBe(first)
  await page.getByRole('button', { name: '暂停鲨鱼动画', exact: true }).click()
  const paused = await frame()
  await page.waitForTimeout(300)
  expect(await frame()).toBe(paused)
  await page.screenshot({ path: 'test-results/sharks/empty-zh.png' })
  await page.getByRole('button', { name: '切换为英文', exact: true }).click()
  await page.screenshot({ path: 'test-results/sharks/empty-en.png' })
  await page.getByRole('button', { name: 'Play shark animation', exact: true }).click()
  await expect.poll(frame).not.toBe(paused)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.getByRole('button', { name: 'Pause shark animation', exact: true })).toBeHidden()
  const still = await frame()
  await page.waitForTimeout(300)
  expect(await frame()).toBe(still)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await expect.poll(frame).not.toBe(still)
  await page.locator('.unified-rail').getByRole('button', { name: 'Exchange', exact: true }).click()
  await expect(canvas).toBeHidden()
  await page.waitForTimeout(150)
  const hidden = await frame()
  await page.waitForTimeout(300)
  expect(await frame()).toBe(hidden)
  await page.locator('.unified-rail').getByRole('button', { name: 'AI Agent', exact: true }).click()
  await expect.poll(frame).not.toBe(hidden)

  // Explicit browser-only history fixture. No real account, model or database calls.
  await page.route('**/api/conversations', route => route.fulfill({ json: { conversations: [{ id: 'shark-ui-fixture', title: 'UI fixture · Portfolio research' }] } }))
  await page.route('**/api/conversations?id=*', route => route.fulfill({ json: { messages: [
    { id: 'u', role: 'user', content: 'How should I compare a Hong Kong equity and gold portfolio?', meta: {}, status: 'complete' },
    { id: 'a', role: 'assistant', content: 'UI fixture — not investment advice or a live model response.\n\nCompare allocation, drawdown, rebalancing costs and the same historical period. A backtest is historical evidence, not a forecast.\n\nKeep enough cash for your needs and review the assumptions before paper execution.', meta: {}, status: 'complete' },
  ] } }))
  await page.goto('/dashboard?enter=workspace')
  await expect(canvas).toBeVisible()
  await expect(page.locator('.agent-chat-messages')).toContainText('UI fixture — not investment advice')
  await expect(canvas.locator('..')).toHaveAttribute('data-subdued', 'true')
  const input = page.locator('.agent-chat-composer input')
  await input.fill('Draft stays editable above the background')
  await expect(input).toHaveValue('Draft stays editable above the background')
  await page.getByRole('button', { name: 'Pause shark animation', exact: true }).click()
  const controlBox = await page.getByRole('button', { name: 'Play shark animation', exact: true }).boundingBox()
  const messagesBox = await page.locator('.agent-chat-messages').boundingBox()
  expect(controlBox!.y + controlBox!.height).toBeLessThanOrEqual(messagesBox!.y)
  await page.screenshot({ path: 'test-results/sharks/history-en.png' })
  await page.getByRole('button', { name: 'Switch to Chinese', exact: true }).click()
  await page.screenshot({ path: 'test-results/sharks/history-zh.png' })
  expect(errors).toEqual([])
})
