import { test, expect, type Page } from '@playwright/test'
import { readFileSync } from 'node:fs'

// Opt-in, isolated temporary accounts only. Never uses the paid model endpoint:
// the weather question exercises the existing deterministic scope refusal.
test('real Supabase login, cloud persistence, two-account separation and logout', async ({ browser }, info) => {
  test.skip(!process.env.ACCOUNT_TEST_FILE || info.project.name !== 'desktop', 'Requires isolated test accounts')
  test.setTimeout(180_000)
  const [a, b] = JSON.parse(readFileSync(process.env.ACCOUNT_TEST_FILE!, 'utf8')) as { email: string; password: string }[]
  const contextA = await browser.newContext({ baseURL: 'http://localhost:3107', viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
  const contextB = await browser.newContext({ baseURL: 'http://localhost:3107', viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
  const pageA = await contextA.newPage()
  const pageB = await contextB.newPage()
  const errors: string[] = []
  pageA.on('pageerror', error => errors.push(error.message))
  pageB.on('pageerror', error => errors.push(error.message))
  const signIn = async (page: Page, user: typeof a) => {
    await page.goto('/login')
    await page.getByLabel('邮箱', { exact: true }).fill(user.email)
    await page.getByLabel('密码', { exact: true }).fill(user.password)
    await page.getByRole('button', { name: '登录', exact: true }).click()
    await page.waitForURL('**/dashboard')
    await expect(page.getByRole('link', { name: '我的账号', exact: true })).toBeVisible({ timeout: 30_000 })
  }
  try {
    await pageA.goto('/login')
    await expect(pageA.getByRole('heading', { name: '欢迎回来' })).toBeVisible()
    await pageA.screenshot({ path: 'test-results/accounts-login-zh.png' })
    await pageA.getByRole('button', { name: 'English', exact: true }).click()
    await expect(pageA.getByRole('heading', { name: 'Welcome back' })).toBeVisible()
    await pageA.screenshot({ path: 'test-results/accounts-login-en.png' })
    await pageA.getByRole('button', { name: '中文', exact: true }).click()
    await signIn(pageA, a)
    await pageA.goto('/account')
    await expect(pageA.getByLabel('昵称', { exact: true })).toHaveValue('QA A')
    await pageA.getByLabel('昵称', { exact: true }).fill('Alice researcher')
    await pageA.getByRole('button', { name: '保存资料', exact: true }).click()
    await expect(pageA.getByRole('status')).toContainText('个人资料已保存')
    await pageA.getByLabel('标的代码，例如 AAPL、BTC').fill('BTC')
    await pageA.getByRole('button', { name: '加入自选', exact: true }).click()
    await expect(pageA.locator('.account-watch-item')).toContainText('BTC')
    expect((await pageA.request.patch('/api/progress', { data: { name: 'Alice', storyStep: 3, lessonStep: 2 } })).status()).toBe(200)
    await pageA.reload()
    await expect(pageA.getByLabel('昵称', { exact: true })).toHaveValue('Alice researcher')
    await pageA.screenshot({ path: 'test-results/accounts-profile.png' })
    const chat = await pageA.request.post('/api/chat', { data: { messages: [{ role: 'user', content: '今天天气怎么样？' }], lang: 'zh' } })
    expect(chat.status()).toBe(200)
    expect(await chat.text()).toContain('范围')
    const conversation = chat.headers()['x-conversation-id']
    expect(conversation).toBeTruthy()
    await signIn(pageB, b)
    await pageB.goto('/account')
    await expect(pageB.getByLabel('昵称', { exact: true })).toHaveValue('QA B')
    await expect(pageB.locator('.account-watch-item')).toHaveCount(0)
    expect((await pageB.request.get(`/api/conversations?id=${conversation}`)).status()).toBe(404)
    expect((await (await pageB.request.get('/api/progress')).json()).state.lessonStep).toBe(0)
    expect((await (await pageB.request.get('/api/conversations')).json()).conversations).toHaveLength(0)
    expect((await pageB.request.patch('/api/profile', { data: { display_name: 'Bad', id: 'another-user' } })).status()).toBe(400)
    await pageA.goto('/dashboard')
    await pageA.locator('.night-entry-card--academy').click()
    await expect(pageA.locator('.unified-workspace')).toBeVisible({ timeout: 30_000 })
    await expect.poll(async () => (await (await pageA.request.get('/api/progress')).json()).state.lessonStep).toBe(2)
    await pageA.getByRole('button', { name: /AI 助手|AI Agent/ }).click()
    await expect(pageA.locator('#chat-history option')).toHaveCount(2)
    await pageA.locator('#chat-history').selectOption(conversation)
    await expect(pageA.locator('.agent-chat-messages')).toContainText('今天天气怎么样')
    await pageA.screenshot({ path: 'test-results/accounts-chat-history.png' })
    await pageA.goto('/account')
    await pageA.getByRole('button', { name: '退出登录', exact: true }).click()
    await pageA.waitForURL('**/login')
    expect((await pageA.request.get('/api/progress')).status()).toBe(401)
    expect((await pageA.request.post('/api/chat', { data: { messages: [{ role: 'user', content: 'Hello' }] } })).status()).toBe(401)
    expect(errors).toEqual([])
  } finally { await contextA.close(); await contextB.close() }
})
