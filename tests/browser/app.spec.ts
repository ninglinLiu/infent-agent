test('desktop house opens an AI-first workspace with five shared navigation entries', async ({ page }, info) => {
  test.skip(info.project.name !== 'desktop', 'The unified workspace is desktop only')
  await page.route('**/api/market/**', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"error":"Test fixture unavailable"}' }))
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/dashboard')
  await expect(page.locator('.night-entry-card')).toHaveCount(3)
  await expect(page.locator('.night-study')).toHaveAttribute('data-scene-ready', 'true', { timeout: 45000 })
  await page.locator('.night-entry-card--workspace').click()
  const shell = page.locator('.unified-workspace')
  const rail = shell.getByRole('navigation', { name: /主导航|Main navigation/ })
  await expect(shell).toBeVisible()
  await expect(shell).toHaveAttribute('data-section', 'ai')
  await expect(rail.getByRole('button')).toHaveCount(5)
  const chat = page.locator('.unified-chat')
  const box = await chat.boundingBox()
  // The split applies to the usable workspace, excluding shared navigation/chrome.
  const workspace = await page.locator('.unified-ai').boundingBox()
  const viewport = page.viewportSize()!
  expect(workspace!.width * workspace!.height / (viewport.width * viewport.height)).toBeGreaterThanOrEqual(0.8)
  // 对话是主体，右侧研究画布占较小的一列
  const canvas = await shell.locator('.research-canvas').boundingBox()
  expect(box!.width).toBeGreaterThan(canvas!.width)
  expect(box!.width / (workspace!.width - 32)).toBeGreaterThanOrEqual(0.5)
  await expect(shell.locator('.research-canvas')).toContainText(/行情源暂不可用|Feed unavailable/)
  await chat.locator('input[maxlength="4000"]').fill('Draft research question')
  await rail.getByRole('button', { name: /交易所|Exchange/ }).click()
  await expect(shell.locator('[data-view="markets"]')).toBeVisible()
  const tabs = shell.getByRole('navigation', { name: 'Exchange', exact: true })
  await expect(tabs.getByRole('button')).toHaveCount(2)
  await tabs.getByRole('button', { name: /模拟组合|Paper portfolio/ }).click()
  await expect(shell.locator('[data-view="portfolio"]')).toBeVisible()
  await expect(shell.locator('[data-view="portfolio"]')).toContainText(/还没有持仓|No positions yet/)
  await tabs.getByRole('button', { name: /全球市场|Markets/ }).click()
  await expect(shell.locator('[data-view="markets"]')).toBeVisible()
  await rail.getByRole('button', { name: /AI 助手|AI Agent/ }).click()
  await expect(chat.locator('input[maxlength="4000"]')).toHaveValue('Draft research question')
  await rail.getByRole('button', { name: /关于|About/ }).click()
  await expect(shell.locator('.unified-about a[href="/"]')).toBeVisible()
  await rail.getByRole('button', { name: /回到房子|House/ }).click()
  await expect(shell).toBeHidden()
  await expect(page.locator('.night-entry-card--markets')).toBeVisible()
  await page.locator('.night-entry-card--markets').click()
  await expect(shell).toHaveAttribute('data-section', 'exchange')
  await rail.getByRole('button', { name: /AI 助手|AI Agent/ }).click()
  await expect(chat.locator('input[maxlength="4000"]')).toHaveValue('Draft research question')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  expect(errors).toEqual([])
})

test('PWA exposes PNG icon, installs a worker and serves its offline notice', async ({ page, context, request }) => {
  const manifest = await (await request.get('/manifest.webmanifest')).json()
  expect(manifest.display).toBe('standalone')
  const icon = await request.get(manifest.icons[0].src)
  expect(icon.headers()['content-type']).toContain('image/png')
  await page.goto('/')
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.reload()
  await expect.poll(() => page.evaluate(() => Boolean(navigator.serviceWorker.controller))).toBe(true)
  await context.setOffline(true)
  await page.goto('/dashboard')
  await expect(page.getByRole('heading', { name: /You are offline/ })).toBeVisible()
  await context.setOffline(false)
})


test('learning room keeps lessons and mentors without duplicating the financial console', async ({ page }, info) => {
  test.skip(info.project.name !== 'desktop', 'The night study is desktop only')
  await page.goto('/dashboard')
  await expect(page.locator('.night-study')).toHaveAttribute('data-scene-ready', 'true', { timeout: 45000 })
  await page.locator('.night-scene').press('l')
  const room = page.locator('.academy-room')
  await expect(room).toBeVisible()
  await page.getByRole('button', { name: '以研究员身份进入' }).click()
  for (const name of ['接过研究员手册', '了解今天的任务', '进入学习室']) {
    await page.getByRole('button', { name, exact: true }).click()
  }
  await expect(room.locator('[data-academy-view="workspace"]')).toBeVisible()
  await expect(room.locator('a[href*="tradingview"], input[maxlength="4000"]')).toHaveCount(0)
  await expect(room.getByText('组合净值', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '开始第一节短课' }).click()
  await expect(room.getByRole('heading', { name: '回撤：你真正要承受的数字', exact: true })).toBeVisible()
  await expect(room.getByRole('img', { name: 'SPY 2020 年真实走势', exact: true })).toBeVisible()
  // A wrong answer explains itself and does not unlock the next lesson.
  await room.locator('.study-options button').first().click()
  await expect(room.locator('.study-why.wrong')).toBeVisible()
  await expect(room.getByRole('button', { name: '下一节', exact: true })).toHaveCount(0)
  await room.locator('.study-options button').nth(1).click()
  await page.getByRole('button', { name: '下一节', exact: true }).click()
  await page.keyboard.press('Escape')
  await page.locator('.night-scene').press('l')
  await room.getByRole('button', { name: '知识短课', exact: true }).click()
  await room.getByRole('button', { name: /仓位：决定你能不能活下来/ }).click()
  await expect(room.getByRole('heading', { name: '仓位：决定你能不能活下来', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '切换为英文', exact: true }).click()
  await expect(room.getByRole('heading', { name: 'Position size: whether you survive', exact: true })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await page.reload()
  await page.locator('.night-scene').press('l')
  await room.getByRole('button', { name: 'Lessons', exact: true }).click()
  await expect(room.getByRole('heading', { name: 'Position size: whether you survive', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Switch to Chinese', exact: true }).click()
  await room.getByRole('button', { name: '历史复盘', exact: true }).click()
  // Replays stop at a decision point and never reveal what comes after it.
  await room.locator('.study-case').first().click()
  await expect(room.locator('.study-decision.ready')).toBeVisible({ timeout: 15000 })
  await expect(room.locator('.study-event time')).toHaveText('2020-02-28')
  await expect(room.locator('.study-result')).toHaveCount(0)
  await page.getByRole('button', { name: '回到房子', exact: true }).click()
  await page.locator('.night-scene').press('Enter')
  await expect(page.locator('.unified-workspace')).toHaveAttribute('data-section', 'ai')
  await expect(page.locator('.academy-room')).toBeHidden()
})
